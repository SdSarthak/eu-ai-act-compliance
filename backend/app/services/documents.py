_INLINE_BOLD = re.compile(r"\*\*(.+?)\*\*")


def _inline_markup(text: str) -> str:
    """Escape the text for reportlab, then re-apply the bold spans."""
    escaped = html.escape(text, quote=False)
    return _INLINE_BOLD.sub(r"<b>\1</b>", escaped)


def _styles():
    sheet = getSampleStyleSheet()
    return {
        "h1": ParagraphStyle(
            "DocH1", parent=sheet["Heading1"], fontSize=18, spaceAfter=10
        ),
        "h2": ParagraphStyle(
            "DocH2", parent=sheet["Heading2"], fontSize=14, spaceBefore=12, spaceAfter=6
        ),
        "h3": ParagraphStyle(
            "DocH3", parent=sheet["Heading3"], fontSize=12, spaceBefore=8, spaceAfter=4
        ),
        "body": ParagraphStyle(
            "DocBody",
            parent=sheet["BodyText"],
            fontSize=10,
            leading=14,
            alignment=TA_LEFT,
        ),
        "bullet": ParagraphStyle(
            "DocBullet", parent=sheet["BodyText"], fontSize=10, leading=14
        ),
    }


def _flush_list(buffer: List[tuple], styles, story: List) -> None:
    """Emit the buffered list items as a single reportlab list flowable."""
    if not buffer:
        return
    kind = buffer[0][0]
    story.append(
        ListFlowable(
            [
                ListItem(Paragraph(_inline_markup(text), styles["bullet"]))
                for _, text in buffer
            ],
            bulletType="bullet" if kind == "bullet" else "1",
            leftIndent=16,
            bulletFontSize=7 if kind == "bullet" else 10,
        )
    )
    story.append(Spacer(1, 4))
    buffer.clear()


def markdown_to_story(content: str, styles) -> List:
    """Translate the generated markdown subset into reportlab flowables."""
    story: List = []
    buffer: List[tuple] = []

    def push(kind: str, text: str) -> None:
        if buffer and buffer[0][0] != kind:
            _flush_list(buffer, styles, story)
        buffer.append((kind, text))

    for raw_line in content.splitlines():
        stripped = raw_line.strip()

        if not stripped:
            _flush_list(buffer, styles, story)
            continue

        if stripped == "---":
            _flush_list(buffer, styles, story)
            story.append(Spacer(1, 6))
            story.append(HRFlowable(width="100%", thickness=0.5))
            story.append(Spacer(1, 6))
            continue

        for prefix, style in (("### ", "h3"), ("## ", "h2"), ("# ", "h1")):
            if stripped.startswith(prefix):
                _flush_list(buffer, styles, story)
                story.append(
                    Paragraph(_inline_markup(stripped[len(prefix):]), styles[style])
                )
                break
        else:
            if stripped.startswith("- ") or stripped.startswith("* "):
                push("bullet", stripped[2:])
                continue

            numbered = re.match(r"^\d+\.\s+(.*)$", stripped)
            if numbered:
                push("number", numbered.group(1))
                continue

            _flush_list(buffer, styles, story)
            story.append(Paragraph(_inline_markup(stripped), styles["body"]))

    _flush_list(buffer, styles, story)
    if not story:
        story.append(Paragraph("This document has no content yet.", styles["body"]))
    return story


def _pdf_filename(document: Document) -> str:
    """A filesystem-safe name derived only from server-controlled fields."""
    version = re.sub(r"[^A-Za-z0-9._-]", "_", str(document.version or "1.0"))
    return f"document-{document.id}-v{version}.pdf"


def export_pdf(document: Document, output_dir: Optional[str] = None) -> str:
    """Render a document to PDF and return the file path.

    The PDF is built into a sibling temporary file and moved into place, so a
    reader downloading the previous export never sees a half-written file and a
    failed build never leaves a truncated PDF behind for the next download to
    serve.
    """
    target_dir = Path(output_dir or settings.DOCUMENT_STORAGE_DIR)
    target_dir.mkdir(parents=True, exist_ok=True)
    path = target_dir / _pdf_filename(document)

    handle, temp_name = tempfile.mkstemp(
        dir=str(target_dir), prefix=f".{path.stem}-", suffix=".part"
    )
    os.close(handle)
    temp_path = Path(temp_name)

    try:
        pdf = SimpleDocTemplate(
            str(temp_path),
            pagesize=A4,
            title=document.title,
            author="EU AI Act Compliance Tool",
            leftMargin=20 * mm,
            rightMargin=20 * mm,
            topMargin=18 * mm,
            bottomMargin=18 * mm,
        )
        pdf.build(markdown_to_story(document.content or "", _styles()))
        os.replace(temp_path, path)
    except OSError:
        # On Windows the replace fails while another request has the target
        # open. A concurrent export produced the same bytes, so keep that one.
        _unlink_quietly(temp_path)
        if not path.exists():
            raise
    except Exception:
        _unlink_quietly(temp_path)
        raise

    return str(path)


def _unlink_quietly(path: Path) -> None:
    """Best-effort delete: a leftover temp file must not mask the real error."""
    try:
        path.unlink(missing_ok=True)
    except OSError:  # pragma: no cover - platform dependent
        logger.warning("Could not remove %s", path)


def remove_pdf(file_path: Optional[str]) -> None:
    """Drop a rendered PDF, tolerating one that is already gone or locked.

    A stale or unreadable file on disk must never stop the database row from
    being deleted, so this never raises.
    """
    if not file_path:
        return
    _unlink_quietly(Path(file_path))


