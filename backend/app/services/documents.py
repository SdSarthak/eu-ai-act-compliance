def _bullet_list(values: List[str], empty: str) -> str:
    if not values:
        return empty
    return "\n".join(f"- {value}" for value in values)


def _numbered_list(values: List[str], empty: str) -> str:
    if not values:
        return empty
    return "\n".join(f"{index}. {value}" for index, value in enumerate(values, 1))


def _checklist_block(items: List[ComplianceItem]) -> str:
    if not items:
        return "No compliance checklist has been generated for this system yet."

    lines = []
    for item in items:
        lines.append(
            f"- {CHECKBOXES[item.status]} **{item.article}** - {item.title} "
            f"({STATUS_LABELS[item.status]})"
        )
        if item.evidence_notes:
            lines.append(f"  - Evidence: {item.evidence_notes}")
    return "\n".join(lines)


def build_context(
    ai_system: AISystem,
    owner: User,
    include_recommendations: bool = True,
) -> Dict[str, str]:
    """Assemble every placeholder a template can reference."""
    assessment = ai_system.latest_assessment
    responses = ai_system.questionnaire_responses or {}

    reasons: List[str] = []
    requirements: List[str] = []
    next_steps: List[str] = []
    articles: List[str] = []
    annex_areas: List[str] = []
    confidence = "not assessed"

    if assessment:
        for finding in assessment.findings or []:
            reasons.extend(finding.get("reasons", []))
            articles.extend(finding.get("applicable_articles", []))
            annex_areas.extend(finding.get("annex_iii_areas", []))
            if finding.get("confidence") is not None:
                confidence = f"{int(round(float(finding['confidence']) * 100))}%"
        for recommendation in assessment.recommendations or []:
            requirements.extend(recommendation.get("requirements", []))
            next_steps.extend(recommendation.get("next_steps", []))

    if not include_recommendations:
        next_steps = []

    risk_level = ai_system.risk_level
    now = datetime.utcnow()

    return {
        "system_name": ai_system.name,
        "version": ai_system.version or "1.0",
        "use_case": ai_system.use_case or responses.get("use_case_category") or "not specified",
        "sector": ai_system.sector or "not specified",
        "description": ai_system.description or "No description has been provided yet.",
        "risk_level": risk_level.value if risk_level else "not assessed",
        "risk_level_label": (
            RISK_LEVEL_LABELS[risk_level] if risk_level else "Not yet assessed"
        ),
        "company_name": owner.company_name or owner.full_name or owner.email,
        "date": now.strftime("%Y-%m-%d"),
        "confidence": confidence,
        "compliance_score": str(ai_system.compliance_score or 0),
        "classification_reasons": _bullet_list(
            reasons, "No classification has been recorded for this system yet."
        ),
        "requirements": _bullet_list(
            requirements, "Run the risk classification to derive the requirements."
        ),
        "next_steps": _numbered_list(
            next_steps, "Run the risk classification to derive the next steps."
        ),
        "applicable_articles": ", ".join(dict.fromkeys(articles)) or "not yet determined",
        "annex_areas": _bullet_list(
            list(dict.fromkeys(annex_areas)),
            "No Annex III area was engaged by the questionnaire answers.",
        ),
        "checklist": _checklist_block(list(ai_system.compliance_items)),
        "footer": "",  # filled in by render_document
    }


def render_document(
    ai_system: AISystem,
    owner: User,
    document_type: DocumentType,
    include_recommendations: bool = True,
) -> str:
    """Render the markdown body of a compliance document."""
    template = TEMPLATES.get(document_type)
    if template is None:
        raise KeyError(f"No template available for {document_type.value}")

    context = build_context(ai_system, owner, include_recommendations)
    context["footer"] = Template(FOOTER).safe_substitute(date=context["date"])
    return Template(template).safe_substitute(context).strip() + "\n"


def next_version(existing: List[Document]) -> str:
    """Documents of the same type for the same system are versioned 1.0, 1.1..."""
    highest = 0
    for document in existing:
        match = re.match(r"^1\.(\d+)$", document.version or "")
        if match:
            highest = max(highest, int(match.group(1)) + 1)
    return f"1.{highest}"


def generate_document(
    db: Session,
    ai_system: AISystem,
    owner: User,
    document_type: DocumentType,
    include_recommendations: bool = True,
) -> Document:
    """Create and persist a generated compliance document."""
    from app.models.document import DocumentStatus

    content = render_document(ai_system, owner, document_type, include_recommendations)

    siblings = [
        document
        for document in ai_system.documents
        if document.document_type == document_type
    ]

    document = Document(
        owner_id=owner.id,
        ai_system_id=ai_system.id,
        title=f"{document_type.value.replace('_', ' ').title()} - {ai_system.name}",
        document_type=document_type,
        status=DocumentStatus.GENERATED,
        content=content,
        version=next_version(siblings),
    )
    db.add(document)
    db.flush()
    return document


